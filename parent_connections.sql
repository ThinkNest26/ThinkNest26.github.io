-- Think Nest: Parent Connections update
--  * Parent directory: partners, parents open to pairing, other parents
--  * Message requests: parents NOT open to pairing approve before others can message them
--  * Parent Groups: parents and hosts create groups, others ask to join
-- Run this once in Supabase: SQL Editor -> New query -> paste -> Run.

-- ---------- helpers ----------
create or replace function public.tn_in_parent_hub()
returns boolean language sql stable security definer set search_path = public as $$
  select coalesce(public.is_hub_member('parents'), false)
      or exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

create or replace function public.tn_my_name()
returns text language sql stable security definer set search_path = public as $$
  select coalesce(full_name, 'A parent') from profiles where id = auth.uid();
$$;

-- ---------- 1. message requests ----------
create table if not exists public.parent_msg_requests (
  id bigint generated by default as identity primary key,
  from_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  to_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'approved', 'declined')),
  created_at timestamptz not null default now(),
  unique (from_id, to_id)
);
alter table public.parent_msg_requests enable row level security;
drop policy if exists pmr_read on public.parent_msg_requests;
create policy pmr_read on public.parent_msg_requests for select to authenticated using (auth.uid() in (from_id, to_id));
drop policy if exists pmr_add on public.parent_msg_requests;
create policy pmr_add on public.parent_msg_requests for insert to authenticated
  with check (from_id = auth.uid() and to_id <> auth.uid() and status = 'pending' and public.tn_in_parent_hub());
drop policy if exists pmr_answer on public.parent_msg_requests;
create policy pmr_answer on public.parent_msg_requests for update to authenticated using (to_id = auth.uid()) with check (to_id = auth.uid());
drop policy if exists pmr_remove on public.parent_msg_requests;
create policy pmr_remove on public.parent_msg_requests for delete to authenticated using (auth.uid() in (from_id, to_id));

-- can I message this parent? 'ok', 'ask' (send a request), 'pending' or 'declined'
create or replace function public.parent_can_message(other uuid)
returns text language plpgsql stable security definer set search_path = public as $$
declare st text;
begin
  -- the rule is only for parent-only accounts messaging each other
  if not exists (select 1 from profiles where id = auth.uid() and role = 'parent')
     or not exists (select 1 from profiles where id = other and role = 'parent') then return 'ok'; end if;
  if exists (select 1 from coffee_matches where hub = 'parents'
             and ((user_a = auth.uid() and user_b = other) or (user_b = auth.uid() and user_a = other))) then return 'ok'; end if;
  if exists (select 1 from hub_profiles where user_id = other and hub = 'parents' and roulette) then return 'ok'; end if;
  select status into st from parent_msg_requests
   where (from_id = auth.uid() and to_id = other) or (from_id = other and to_id = auth.uid() and status = 'approved')
   order by (status = 'approved') desc limit 1;
  if st = 'approved' then return 'ok'; end if;
  return coalesce(st, 'ask');
end $$;
grant execute on function public.parent_can_message(uuid) to authenticated;

-- ---------- 2. parent groups ----------
create table if not exists public.parent_groups (
  id bigint generated by default as identity primary key,
  name text not null check (length(trim(name)) between 2 and 80),
  about text check (about is null or length(about) <= 600),
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  owner_name text,
  created_at timestamptz not null default now()
);
create table if not exists public.parent_group_members (
  group_id bigint not null references public.parent_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_name text,
  role text not null default 'member' check (role in ('owner', 'member')),
  status text not null default 'pending' check (status in ('pending', 'active')),
  created_at timestamptz not null default now(),
  primary key (group_id, user_id)
);
create table if not exists public.parent_group_posts (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.parent_groups(id) on delete cascade,
  author_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  author_name text,
  body text not null check (length(trim(body)) between 1 and 2000),
  link text check (link is null or link ~* '^https?://'),
  created_at timestamptz not null default now()
);

create or replace function public.pg_is_member(gid bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from parent_group_members where group_id = gid and user_id = auth.uid() and status = 'active');
$$;
create or replace function public.pg_is_owner(gid bigint)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from parent_groups where id = gid and owner_id = auth.uid())
      or exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

-- names always come from the profile (can't be faked)
create or replace function public.tn_pg_names()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_table_name = 'parent_groups' then new.owner_id := auth.uid(); new.owner_name := public.tn_my_name();
  elsif tg_table_name = 'parent_group_posts' then new.author_id := auth.uid(); new.author_name := public.tn_my_name();
  elsif tg_table_name = 'parent_group_members' then
    select coalesce(full_name, 'A parent') into new.user_name from profiles where id = new.user_id;
  end if;
  return new;
end $$;
drop trigger if exists tn_pg_names on public.parent_groups;
create trigger tn_pg_names before insert on public.parent_groups for each row execute function public.tn_pg_names();
drop trigger if exists tn_pg_names on public.parent_group_posts;
create trigger tn_pg_names before insert on public.parent_group_posts for each row execute function public.tn_pg_names();
drop trigger if exists tn_pg_names on public.parent_group_members;
create trigger tn_pg_names before insert on public.parent_group_members for each row execute function public.tn_pg_names();

-- the creator becomes the group's owner
create or replace function public.tn_pg_owner()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into parent_group_members (group_id, user_id, role, status) values (new.id, new.owner_id, 'owner', 'active')
  on conflict (group_id, user_id) do nothing;
  return new;
end $$;
drop trigger if exists tn_pg_owner on public.parent_groups;
create trigger tn_pg_owner after insert on public.parent_groups for each row execute function public.tn_pg_owner();

alter table public.parent_groups enable row level security;
alter table public.parent_group_members enable row level security;
alter table public.parent_group_posts enable row level security;

drop policy if exists pg_read on public.parent_groups;
create policy pg_read on public.parent_groups for select to authenticated using (public.tn_in_parent_hub());
drop policy if exists pg_add on public.parent_groups;
create policy pg_add on public.parent_groups for insert to authenticated with check (public.tn_in_parent_hub());
drop policy if exists pg_edit on public.parent_groups;
create policy pg_edit on public.parent_groups for update to authenticated using (public.pg_is_owner(id)) with check (public.pg_is_owner(id));
drop policy if exists pg_remove on public.parent_groups;
create policy pg_remove on public.parent_groups for delete to authenticated using (public.pg_is_owner(id));

drop policy if exists pgm_read on public.parent_group_members;
create policy pgm_read on public.parent_group_members for select to authenticated
  using (user_id = auth.uid() or public.pg_is_member(group_id) or public.pg_is_owner(group_id));
drop policy if exists pgm_add on public.parent_group_members;
create policy pgm_add on public.parent_group_members for insert to authenticated with check (
  public.tn_in_parent_hub() and role = 'member' and (
    (user_id = auth.uid() and status = 'pending')     -- ask to join
    or public.pg_is_owner(group_id)                    -- the owner adds someone
  ));
drop policy if exists pgm_approve on public.parent_group_members;
create policy pgm_approve on public.parent_group_members for update to authenticated
  using (public.pg_is_owner(group_id)) with check (public.pg_is_owner(group_id) and role = 'member');
drop policy if exists pgm_remove on public.parent_group_members;
create policy pgm_remove on public.parent_group_members for delete to authenticated
  using ((user_id = auth.uid() and role <> 'owner') or (public.pg_is_owner(group_id) and role <> 'owner'));

drop policy if exists pgp_read on public.parent_group_posts;
create policy pgp_read on public.parent_group_posts for select to authenticated using (public.pg_is_member(group_id) or public.pg_is_owner(group_id));
drop policy if exists pgp_add on public.parent_group_posts;
create policy pgp_add on public.parent_group_posts for insert to authenticated with check (public.pg_is_member(group_id));
drop policy if exists pgp_remove on public.parent_group_posts;
create policy pgp_remove on public.parent_group_posts for delete to authenticated using (author_id = auth.uid() or public.pg_is_owner(group_id));

-- ---------- 3. notifications ----------
create or replace function public.tn_pc_notify()
returns trigger language plpgsql security definer set search_path = public as $$
declare gname text; gowner uuid;
begin
  if tg_table_name = 'parent_msg_requests' then
    if tg_op = 'INSERT' then
      insert into notifications (user_id, title, kind, link)
      values (new.to_id, '✉️ ' || coalesce((select full_name from profiles where id = new.from_id), 'A parent') || ' would like to message you', 'friend', 'parent-connect.html#people');
    elsif new.status = 'approved' and old.status <> 'approved' then
      insert into notifications (user_id, title, kind, link)
      values (new.from_id, '✅ ' || coalesce((select full_name from profiles where id = new.to_id), 'A parent') || ' said yes. You can message them now', 'friend', 'parent-connect.html#people');
    end if;
  else
    select name, owner_id into gname, gowner from parent_groups where id = new.group_id;
    if tg_op = 'INSERT' and new.status = 'pending' then
      insert into notifications (user_id, title, kind, link)
      values (gowner, '👥 ' || coalesce(new.user_name, 'A parent') || ' asked to join ' || coalesce(gname, 'your group'), 'friend', 'parent-group.html?id=' || new.group_id);
    elsif new.role = 'member' and new.status = 'active' and (tg_op = 'INSERT' or old.status = 'pending') then
      insert into notifications (user_id, title, kind, link)
      values (new.user_id, '👥 You’re now a member of ' || coalesce(gname, 'a parent group'), 'friend', 'parent-group.html?id=' || new.group_id);
    end if;
  end if;
  return new;
end $$;
drop trigger if exists tn_pc_notify on public.parent_msg_requests;
create trigger tn_pc_notify after insert or update on public.parent_msg_requests for each row execute function public.tn_pc_notify();
drop trigger if exists tn_pc_notify on public.parent_group_members;
create trigger tn_pc_notify after insert or update on public.parent_group_members for each row execute function public.tn_pc_notify();
