  const norm = s => s.replace(/\s+/g, ' ').trim();
  const ATTRS = ['placeholder', 'aria-label', 'title'];
  function tr(root) {
    if (lang !== 'ar' || !root) return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = []; let n; while ((n = w.nextNode())) nodes.push(n);
    nodes.forEach(t => {
      const p = t.parentElement; if (!p || /^(SCRIPT|STYLE|TEXTAREA|CODE)$/.test(p.tagName) || p.closest('[data-no-tr]')) return;
      const k = norm(t.textContent); if (!k || !AR[k]) return;
      const lead = t.textContent.match(/^\s*/)[0], trail = t.textContent.match(/\s*$/)[0];
      t.textContent = lead + AR[k] + trail;
    });
    (root.querySelectorAll ? root.querySelectorAll('[placeholder],[aria-label],[title],input[type=submit],input[type=button]') : []).forEach(el => {
      ATTRS.forEach(a => { const v = el.getAttribute(a); if (v && AR[norm(v)]) el.setAttribute(a, AR[norm(v)]); });
      if ((el.type === 'submit' || el.type === 'button') && el.value && AR[norm(el.value)]) el.value = AR[norm(el.value)];
    });
    if (document.title && AR[norm(document.title.replace(/ – Think Nest$/, ''))]) document.title = AR[norm(document.title.replace(/ – Think Nest$/, ''))] + ' – ثينك نست';
  }
  window.tnTranslate = tr;
  function switcher() {
    if (document.getElementById('tn-lang')) return;
    const b = document.createElement('button');
    b.type = 'button'; b.id = 'tn-lang'; b.className = 'tn-lang';
    b.setAttribute('aria-label', lang === 'ar' ? 'Switch to English' : 'التبديل إلى العربية');
    b.innerHTML = lang === 'ar' ? '🌐 English' : '🌐 عربي';
    b.setAttribute('data-no-tr', '');
    b.addEventListener('click', () => { try { localStorage.setItem('tn_lang', lang === 'ar' ? 'en' : 'ar'); } catch (_) {} location.reload(); });
    const spot = document.querySelector('.nav-buttons') || document.querySelector('.bar-right') || document.querySelector('.app-top .app-exit') || null;
    if (spot && spot.classList.contains('app-exit')) spot.parentNode.insertBefore(b, spot);
    else if (spot) spot.prepend(b);
    else { b.classList.add('floating'); document.body.appendChild(b); }
  }
  document.addEventListener('DOMContentLoaded', () => {
    switcher();
    if (lang !== 'ar') return;
    tr(document.body);
    // anything added or changed later (menus, tours, messages) is translated too
    let queued = false;
    new MutationObserver(() => {
      if (queued) return; queued = true;
      requestAnimationFrame(() => { queued = false; tr(document.body); });
    }).observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'title'] });
  });
